#!/usr/bin/env python3
"""Part 4 analysis: medians, speed-up, efficiency and communication share, with plots.

Run from the repo root:   python3 scripts/analyze_scaling.py
Reads   results/baseline_heat-*.txt  and the newest  results/scaling_{local,slot,node}_*.txt
Writes  results/scaling_summary.md  and four PNG figures in results/.

Every time is converted to seconds per step, so runs with different --steps can be compared.
Blocks are only measured at P = 4, 6, 8; for other P the block layout is one block wide,
which is the strip layout, so the strip value applies.
"""
import glob, os, re, statistics, sys
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

KV = re.compile(r"(\w+)=(\S+)")
BLUE, ORANGE, AQUA = "#257de0", "#f47230", "#00b894"
INK, MUTED, GRID = "#191919", "#666666", "#e3e3e3"
plt.rcParams.update({"font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK,
                     "xtick.color": MUTED, "ytick.color": MUTED, "text.color": INK,
                     "axes.spines.top": False, "axes.spines.right": False,
                     "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6,
                     "lines.linewidth": 2, "lines.markersize": 6, "legend.frameon": False})


def read_runs(path):
    """Return {(decomp, P, N): [per-run dicts]} for one results file."""
    runs = defaultdict(list)
    for line in open(path):
        if line.startswith("#") or "t_total=" not in line:
            continue
        kv = dict(KV.findall(line))
        steps, N = int(kv["steps"]), int(kv["N"])
        runs[(kv["decomp"], int(kv["P"]), N)].append({
            "step": float(kv["t_total"]) / steps,                 # seconds per time step
            "share": float(kv["t_comm"]) / float(kv["t_total"]),  # fraction spent in halo exchange
            "grid": f'{kv.get("Px", "1")}x{kv.get("Py", kv["P"])}',
        })
    return runs


def summarise(runs):
    """Median, min and max of the time per step, speed-up, efficiency, communication share."""
    out = {}
    for (decomp, P, N), rs in runs.items():
        t = [r["step"] for r in rs]
        out[(decomp, P, N)] = {"t": statistics.median(t), "lo": min(t), "hi": max(t), "n": len(t),
                               "share": statistics.median(r["share"] for r in rs), "grid": rs[0]["grid"]}
    for (decomp, P, N), s in out.items():
        base = out.get(("strips", 1, N)) or out.get(("serial", 1, N))
        s["S"] = base["t"] / s["t"] if base else float("nan")
        s["E"] = s["S"] / P
    return out


def newest(pattern):
    files = sorted(glob.glob(pattern))
    return files[-1] if files else None


# ---------------------------------------------------------------- baseline (experiment 1)
baseline = {}
for path in sorted(glob.glob("results/baseline_heat-*.txt")):
    host = os.path.basename(path)[len("baseline_"):-len(".txt")]
    per_n = defaultdict(list)
    for line in open(path):
        kv = dict(KV.findall(line))
        if "t_total" in kv:
            N, steps = int(kv["N"]), int(kv["steps"])
            per_n[N].append(float(kv["t_total"]) / steps)
    baseline[host] = {N: statistics.median(v) for N, v in sorted(per_n.items())}

# ---------------------------------------------------------------- scaling (experiment 2)
modes = {}
for mode in ("local", "slot", "node"):
    path = newest(f"results/scaling_{mode}_*.txt")
    if path:
        modes[mode] = (path, summarise(read_runs(path)))
if not modes:
    sys.exit("no results/scaling_*.txt files found")

LABEL = {"local": "one VM (heat-ali), 500 steps", "slot": "cluster, fill one VM first (--map-by slot)",
         "node": "cluster, round-robin (--map-by node)"}

# ---------------------------------------------------------------- summary tables
md = ["# Part 4 summary", "",
      "Generated by scripts/analyze_scaling.py. Times are medians of the repeats, in milliseconds per",
      "time step; the range is the fastest and slowest repeat. Speed-up S = T1 / TP against one process",
      "in the same session; efficiency E = S / P; share = fraction of the run spent in halo exchange.", ""]
if baseline:
    ns = sorted({N for b in baseline.values() for N in b})
    md += ["## Experiment 1: serial baseline, nanoseconds per node update", "",
           "| VM | " + " | ".join(f"N = {N}" for N in ns) + " |", "|---|" + "---|" * len(ns)]
    for host, b in baseline.items():
        md.append(f"| {host} | " + " | ".join(
            f"{b[N] / (N - 1) ** 2 * 1e9:.2f}" if N in b else "" for N in ns) + " |")
    md.append("")
for mode, (path, s) in modes.items():
    md += [f"## Experiment 2: strong scaling, {LABEL[mode]}", "", f"Source: `{path}`", ""]
    for N in sorted({k[2] for k in s}):
        md += [f"**N = {N}**", "", "| Decomposition | P | Grid Px x Py | ms per step | Range | S | E | Share |",
               "|---|---|---|---|---|---|---|---|"]
        for decomp in ("strips", "blocks"):
            for P in sorted({k[1] for k in s if k[0] == decomp and k[2] == N}):
                r = s[(decomp, P, N)]
                md.append(f"| {decomp} | {P} | {r['grid']} | {r['t'] * 1e3:.3g} | "
                          f"{r['lo'] * 1e3:.3g} to {r['hi'] * 1e3:.3g} | {r['S']:.3g} | {r['E']:.3g} | "
                          f"{r['share'] * 100:.0f}% |")
        md.append("")
open("results/scaling_summary.md", "w").write("\n".join(md))
print("\n".join(md))

# ---------------------------------------------------------------- figures
cluster = [m for m in ("slot", "node") if m in modes] or list(modes)
sizes = sorted({k[2] for m in cluster for k in modes[m][1]})
# colour = decomposition, line style and marker = placement
STYLE = {("slot", "strips"): (BLUE, "-", "o"), ("slot", "blocks"): (ORANGE, "-", "s"),
         ("node", "strips"): (BLUE, "--", "^"), ("node", "blocks"): (ORANGE, "--", "D"),
         ("local", "strips"): (BLUE, "-", "o"), ("local", "blocks"): (ORANGE, "-", "s")}
NAME = {"slot": "fill one VM first", "node": "round-robin", "local": "one VM"}


NOTE = ("Blocks are measured at P = 4, 6, 8; for other P the block grid is one block wide, "
        "i.e. the strip layout. Medians of 3 runs.")


def legend(fig, ax):
    """One legend for the whole figure, under the title, so it never covers data."""
    handles, labels = ax.get_legend_handles_labels()
    top = 0.955 if fig.get_figheight() > 5 else 0.915
    fig.legend(handles, labels, loc="upper left", bbox_to_anchor=(0.01, top), ncol=4, fontsize=8.5,
               handlelength=3.2, columnspacing=2.2)


def draw(ax, pts, mode, decomp):
    """Strips: line with markers. Blocks: markers only, since they are measured at P = 4, 6, 8."""
    colour, ls, mk = STYLE[(mode, decomp)]
    if decomp == "blocks":
        pts = [(p, v) for p, v in pts if p in (4, 6, 8)]
        ax.plot([p for p, _ in pts], [v for _, v in pts], color=colour, linestyle="none", marker=mk,
                markersize=8, markeredgecolor="white", markeredgewidth=1.2, zorder=3,
                label=f"blocks, {NAME[mode]}")
    else:
        ax.plot([p for p, _ in pts], [v for _, v in pts], color=colour, linestyle=ls, marker=mk,
                markeredgecolor="white", markeredgewidth=1, label=f"strips, {NAME[mode]}")


def panel(ax, N, key):
    for mode in cluster:
        s = modes[mode][1]
        for decomp in ("strips", "blocks"):
            pts = sorted((P, r[key]) for (d, P, n), r in s.items() if d == decomp and n == N)
            if not pts:
                continue
            draw(ax, pts, mode, decomp)
    ax.set_title(f"N = {N}", loc="left", fontsize=10, fontweight="bold")
    ax.set_xticks(range(1, 9))


fig, axes = plt.subplots(2, len(sizes), figsize=(4.2 * len(sizes), 7), sharex=True, squeeze=False)
for c, N in enumerate(sizes):
    for r, (key, name) in enumerate((("S", "Speed-up  S = T1 / TP"), ("E", "Efficiency  E = S / P"))):
        ax = axes[r][c]
        panel(ax, N, key)
        ax.set_yscale("log")
        ax.axhline(1, color=MUTED, linewidth=1)
        if c == 0:
            ax.set_ylabel(name + "  (log scale)")
        if r == 1:
            ax.set_xlabel("Processes P")
        else:
            ax.text(8, 1, "no gain: S = 1 ", ha="right", va="bottom", color=MUTED, fontsize=8)
legend(fig, axes[0][0])
fig.suptitle("Strong scaling on the cluster: only the runs that stay on one VM (P ≤ 4, fill one VM first) gain",
             x=0.01, ha="left", fontsize=11, fontweight="bold")
fig.text(0.01, 0.005, NOTE, color=MUTED, fontsize=8)
fig.tight_layout(rect=(0, 0.02, 1, 0.93))
fig.savefig("results/scaling_speedup_efficiency.png", dpi=150)

fig, axes = plt.subplots(1, len(sizes), figsize=(4.2 * len(sizes), 3.8), sharey=True, squeeze=False)
for c, N in enumerate(sizes):
    ax = axes[0][c]
    for mode in cluster:
        s = modes[mode][1]
        for decomp in ("strips", "blocks"):
            pts = sorted((P, r["share"] * 100) for (d, P, n), r in s.items() if d == decomp and n == N)
            if pts:
                draw(ax, pts, mode, decomp)
    ax.set_title(f"N = {N}", loc="left", fontsize=10, fontweight="bold")
    ax.set_xticks(range(1, 9)); ax.set_xlabel("Processes P"); ax.set_ylim(0, 105)
    if c == 0:
        ax.set_ylabel("Share of run time in halo exchange (%)")
legend(fig, axes[0][0])
fig.suptitle("Communication share: once a run crosses VMs, the exchange is almost the whole run",
             x=0.01, ha="left", fontsize=11, fontweight="bold")
fig.text(0.01, 0.005, NOTE, color=MUTED, fontsize=8)
fig.tight_layout(rect=(0, 0.03, 1, 0.88))
fig.savefig("results/scaling_comm_share.png", dpi=150)

fig, axes = plt.subplots(1, len(sizes), figsize=(4.2 * len(sizes), 3.8), squeeze=False)
for c, N in enumerate(sizes):
    ax = axes[0][c]
    panel(ax, N, "t")
    ax.set_yscale("log"); ax.set_xlabel("Processes P")
    if c == 0:
        ax.set_ylabel("Seconds per time step  (log scale)")
legend(fig, axes[0][0])
fig.suptitle("Time per step: crossing to another VM costs two to four orders of magnitude",
             x=0.01, ha="left", fontsize=11, fontweight="bold")
fig.text(0.01, 0.005, NOTE, color=MUTED, fontsize=8)
fig.tight_layout(rect=(0, 0.03, 1, 0.88))
fig.savefig("results/scaling_time_per_step.png", dpi=150)

if baseline:
    # colour follows the VM; the throttled run is the same VM as heat-rael, drawn dashed and muted
    LOOK = {"heat-ali": (BLUE, "-", "o", 7), "heat-yves": (ORANGE, "-", "s", -7),
            "heat-rael": (AQUA, "-", "^", 0), "heat-rael_throttled": (MUTED, "--", "^", 0)}
    fig, ax = plt.subplots(figsize=(7.5, 4))
    for host, b in baseline.items():
        colour, ls, mk, dy = LOOK.get(host, (MUTED, "-", "D", 0))
        ns = sorted(b)
        ys = [b[N] / (N - 1) ** 2 * 1e9 for N in ns]
        ax.plot(ns, ys, color=colour, linestyle=ls, marker=mk, markeredgecolor="white", markeredgewidth=1)
        name = "heat-rael on battery" if host.endswith("_throttled") else host
        ax.annotate(name, (ns[-1], ys[-1]), xytext=(8, dy), textcoords="offset points", va="center", fontsize=8.5)
    ax.set_xscale("log", base=2); ax.set_xticks(ns); ax.set_xticklabels([str(n) for n in ns])
    ax.set_xlabel("Grid size N"); ax.set_ylabel("Nanoseconds per node update"); ax.set_ylim(0, None)
    ax.set_xlim(None, ns[-1] * 2.6)
    ax.set_title("Serial compute rate per VM", loc="left", fontsize=11, fontweight="bold")
    fig.tight_layout()
    fig.savefig("results/baseline_compute_rate.png", dpi=150)

print("wrote results/scaling_summary.md and the PNG figures in results/")
